start:
    jsr save_state
    lda #0
    sta $d020
    sta $d021
    lda #147
    jsr $ffd2
    jsr show_splash
    jsr initialize
main:
    ; All eight sprite positions and pointers change in the lower border.
    jsr wait_frame
    jsr controls
    lda quitting
    beq keep_running
    jmp exit
keep_running:
    lda paused
    bne main
    ; Normalize NTSC's 60 frames to the same 50 Hz sequencer as PAL.
    lda $02a6
    bne pal_tick
    inc ntsc_divider
    lda ntsc_divider
    cmp #6
    bcc pal_tick
    lda #0
    sta ntsc_divider
    jmp main
pal_tick:
    jsr music_tick
    jsr animate_cat
    jsr animate_meters
    jmp main

save_state:
    ldx #0
save_positions:
    lda $d000,x
    sta old_vic,x
    inx
    cpx #25
    bne save_positions
    ldx #0
save_extra:
    lda $d01b,x
    sta old_extra,x
    inx
    cpx #20
    bne save_extra
    ldx #0
save_pointers:
    lda $07f8,x
    sta old_pointers,x
    inx
    cpx #8
    bne save_pointers
    ldx #0
save_sid:
    lda $d400,x
    sta old_sid,x
    inx
    cpx #25
    bne save_sid
    ldx #0
save_zp:
    lda $fb,x
    sta old_zp,x
    inx
    cpx #4
    bne save_zp
    lda $dd00
    sta old_bank
    lda $0286
    sta old_text_color
    rts

initialize:
    lda #0
    sta $d020
    sta $d015
    sta paused
    sta muted
    sta quitting
    sta unit_tick
    sta song_step
    sta ntsc_divider
    lda #6
    sta $d021
    sta frames_per_unit
    lda old_bank
    ora #3
    sta $dd00
    lda #$1b
    sta $d011
    lda #8
    sta $d016
    lda #$18
    sta $d018
    ldx #0
copy_scene:
    lda scene_screen,x
    sta $0400,x
    lda scene_screen+256,x
    sta $0500,x
    lda scene_screen+512,x
    sta $0600,x
    lda scene_screen+768,x
    sta $0700,x
    lda scene_colors,x
    sta $d800,x
    lda scene_colors+256,x
    sta $d900,x
    lda scene_colors+512,x
    sta $da00,x
    lda scene_colors+768,x
    sta $db00,x
    inx
    bne copy_scene
    ; Frequency tables for the actual machine's SID clock.
    ldx #95
copy_frequencies:
    lda $02a6
    beq copy_ntsc
    lda pal_lo,x
    sta freq_lo,x
    lda pal_hi,x
    sta freq_hi,x
    jmp next_frequency
copy_ntsc:
    lda ntsc_lo,x
    sta freq_lo,x
    lda ntsc_hi,x
    sta freq_hi,x
next_frequency:
    dex
    bpl copy_frequencies
    lda #0
    sta $d010
    sta $d01b
    lda #$ff
    sta $d017
    sta $d01d
    lda #$fc
    sta $d01c
    lda #1
    sta $d025
    lda #15
    sta $d026
    lda #11
    sta $d027
    sta $d028
    ldx #2
sprite_colors:
    lda #10
    sta $d027,x
    inx
    cpx #8
    bne sprite_colors
    jsr initialize_sid
    jsr sequence_step
    jsr animate_cat
    jsr animate_meters
    lda #$ff
    sta $d015
    rts

wait_frame:
    lda #250
wait_line:
    cmp $d012
    bne wait_line
leave_line:
    cmp $d012
    beq leave_line
    rts

music_tick:
    inc unit_tick
    lda unit_tick
    cmp frames_per_unit
    bcc instrument_tick
    lda #0
    sta unit_tick
    inc song_step
    jsr sequence_step
instrument_tick:
    lda muted
    bne tick_done
    ; Release the lead just before a new note, but sustain across tied steps.
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_envelope
    ldx song_step
    inx
    lda melody,x
    beq drum_envelope
    lda #$40
    sta $d404
drum_envelope:
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_release
    lda song_step
    and #1
    beq drum_release
    lda #$10
    sta $d40b
drum_release:
    lda unit_tick
    cmp #2
    bne pulse_motion
    lda #$80
    sta $d412
pulse_motion:
    lda unit_tick
    asl
    asl
    clc
    adc #$40
    sta $d402
tick_done:
    rts

sequence_step:
    lda muted
    bne sequence_done
    ldx song_step
    lda melody,x
    beq accompaniment
    tax
    lda freq_lo,x
    sta $d400
    lda freq_hi,x
    sta $d401
    lda #$41
    sta $d404
accompaniment:
    lda song_step
    and #1
    bne sequence_done
    ; Oom-pah bass: roots/fifths on beats, short upper notes off the beat.
    ldx song_step
    lda bass_notes,x
    tax
    lda freq_lo,x
    sta $d407
    lda freq_hi,x
    sta $d408
    lda #$11
    sta $d40b
    lda song_step
    and #2
    beq bass_drum
    lda #$30
    sta $d40e
    lda #$1c
    sta $d40f
    lda #$02
    sta $d413
    jmp play_drum
bass_drum:
    lda #$40
    sta $d40e
    lda #$03
    sta $d40f
    lda #$04
    sta $d413
play_drum:
    lda #$81
    sta $d412
sequence_done:
    rts

initialize_sid:
    ldx #24
clear_sid:
    lda #0
    sta $d400,x
    dex
    bpl clear_sid
    lda #$08
    sta $d405
    lda #$89
    sta $d406
    lda #$40
    sta $d402
    lda #$08
    sta $d403
    lda #$09
    sta $d40c
    lda #$48
    sta $d40d
    lda #$08
    sta $d414
    lda #15
    sta $d418
    rts

animate_cat:
    ; 16 animation phases per quarter note, tied to the song position.
    lda song_step
    and #3
    asl
    asl
    sta bob_phase
    lda unit_tick
    asl
    cmp frames_per_unit
    bcc first_half
    inc bob_phase
    inc bob_phase
first_half:
    ldx bob_phase
    lda head_x,x
    sta head_origin_x
    lda head_y,x
    sta head_origin_y
    lda head_pose,x
    asl
    asl
    asl
    clc
    adc #$c0
    sta sprite_pointer
    ldx #0
position_sprites:
    lda head_origin_x
    clc
    adc sprite_dx,x
    sta sprite_x
    lda head_origin_y
    clc
    adc sprite_dy,x
    sta sprite_y
    txa
    asl
    tay
    lda sprite_x
    sta $d000,y
    lda sprite_y
    sta $d001,y
    lda sprite_pointer
    sta $07f8,x
    inc sprite_pointer
    inx
    cpx #8
    bne position_sprites
    rts

animate_meters:
    ; Three small rhythm lamps under the bench; no character-ROM graphics.
    lda song_step
    and #7
    tax
    lda lamp_colors,x
    sta $db83
    lda lamp_colors+2,x
    sta $db86
    lda lamp_colors+4,x
    sta $db89
    rts

controls:
    jsr $ffe4
    cmp #81
    bne check_pause
    lda #1
    sta quitting
    rts
check_pause:
    cmp #32
    bne check_mute
    lda paused
    eor #1
    sta paused
    bne quiet
    lda muted
    bne controls_done
    lda #15
    sta $d418
    rts
check_mute:
    cmp #77
    bne check_restart
    lda muted
    eor #1
    sta muted
    bne quiet
    lda paused
    bne quiet
    jsr initialize_sid
    jsr sequence_step
    rts
quiet:
    lda #0
    sta $d418
    rts
check_restart:
    cmp #82
    bne speed_one
    lda #0
    sta song_step
    sta unit_tick
    jsr sequence_step
    rts
speed_one:
    cmp #49
    bne speed_two
    lda #7
    sta frames_per_unit
    rts
speed_two:
    cmp #50
    bne speed_three
    lda #6
    sta frames_per_unit
    rts
speed_three:
    cmp #51
    bne controls_done
    lda #5
    sta frames_per_unit
controls_done:
    rts

show_splash:
    lda #<splash
    sta $fb
    lda #>splash
    sta $fc
print_splash:
    ldy #0
    lda ($fb),y
    beq wait_space
    jsr $ffd2
    inc $fb
    bne print_splash
    inc $fc
    jmp print_splash
wait_space:
    jsr $ffe4
    cmp #32
    bne wait_space
    rts

exit:
    lda #0
    sta $d015
    sta $d418
    ldx #0
