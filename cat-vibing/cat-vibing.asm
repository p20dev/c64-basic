; Visual reference: https://knowyourmeme.com/memes/catjam-vibing-cat
; No recording, lyrics, or sampled audio. One sequencer clocks SID and head bob.
;
; Layout: BASIC $0801, code $1000, custom scene charset $2000,
; four 512-byte sprite poses $3000, screen/color/song tables $4000 onward.
