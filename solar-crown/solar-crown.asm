!cpu 6510
; SOLAR CROWN -- original solar-eclipse bitmap and three-voice SID score.
; Red, orange and yellow corona filaments surround a dark eclipsing disk.
; Twelve cyclic phases; exact multicolor pixels, no ROM glyphs.
; Two VIC banks: bitmap $2000 / screen $0400, bitmap $6000 / screen $4400.
; Only 168 changing tiles are copied, 42 per 50 Hz tick, before a border flip.
; BASIC ROM is banked out temporarily to access patch data; CPU port restored.
; KERNAL IRQs, CIA timers and vectors are untouched. PAL/NTSC pitch tables.
; Original E-minor SID composition: pulse lead, pulse bass and percussion.
; Pause freezes both buffers and sequencing. Exit restores VIC and silences
; SID: write-only SID registers cannot recover a prior tune.
; Layout: code $1000, music $4000, base tiles $4800, tile maps $5400/$5800,
; frequencies / patch positions $5c00, animation pixels $8000-$beff.

* = $0801
!word basic_end,10
!byte $9e
!text "4096"
