!cpu 6510
; CLOUD NINE -- original pixel aircraft, wing-top dancers and SID score.
; Visual nod to the aircraft sequence in O-Zone's Dragostea din tei video:
; https://www.youtube.com/watch?v=jRx5PrAlUdY
; The music is a NEW Eurodance composition, not an arrangement of that song.
; Twelve lossless multicolor bitmap poses: banking, dancers and propellers.
; Two banks: bitmap $2000/screen $0400, bitmap $6000/screen $4400.
; 164 changing tiles, 41 per 50 Hz tick; complete frames flip at raster 250.
; BASIC ROM is temporarily banked out during copying; CPU port restored.
; KERNAL IRQs, CIA timers and vectors untouched. PAL/NTSC pitch tables.
; SID is silenced on exit: write-only registers cannot recover a prior tune.
; Data stays below I/O: code $1000, score $4000, base tiles $4800,
; maps $5400/$5800, pitch/patch tables $5c00, frames $8000-$bd7f.

* = $0801
!word basic_end,10
!byte $9e
!text "4096"
!byte 0
