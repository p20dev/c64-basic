* = $1000
start:
    jsr save_state
    lda #0
    sta $d020
    sta $d021
    lda #147
    jsr $ffd2
    jsr show_splash
    jsr initialize
main:
    jsr wait_frame
    jsr controls
    lda quitting
    beq continue
    jmp exit
continue:
    lda paused
    bne main
    lda pending
    beq no_flip
    jsr flip
no_flip:
    lda $02a6
    bne tick
    inc ntsc_divider
    lda ntsc_divider
    cmp #6
    bcc tick
    lda #0
    sta ntsc_divider
    jmp main
tick:
    jsr music_tick
    lda delay_count
    beq draw
    dec delay_count
    jmp main
draw:
    jsr prepare_part
    jmp main

save_state:
    ldx #0
save_positions:
    lda $d000,x
    sta old_vic,x
    inx
    cpx #25
    bne save_positions
    ldx #0
save_extra:
    lda $d01b,x
    sta old_extra,x
    inx
    cpx #20
    bne save_extra
    ldx #0
save_pointers:
    lda $07f8,x
    sta old_pointers,x
    inx
    cpx #8
    bne save_pointers
    ldx #0
save_zp:
    lda $f9,x
    sta old_zp,x
    inx
    cpx #6
    bne save_zp
    lda $dd00
    sta old_bank
    lda $0286
    sta old_text_color
    rts



initialize:
    lda #0
    sta $d011
    sta $d015
    sta paused
    sta muted
    sta quitting
    sta pending
    sta render_part
    sta song_step
    sta unit_tick
    sta ntsc_divider
    sta delay_count
    lda #1
    sta phase
    sta speed_delay
    lda #5
    sta base_frames
    sta frames_per_unit
    lda #$40
    sta hidden_mask
    lda old_bank
    ora #3
    sta $dd00
    lda #$18
    sta $d018
    sta $d016
    ; Static per-cell colors are identical in both VIC banks.
    ldx #0
init_colors:
    lda #$e3
    sta $0400,x
    sta $0500,x
    sta $0600,x
    sta $0700,x
    sta $4400,x
    sta $4500,x
    sta $4600,x
    sta $4700,x
    lda #1
    sta $d800,x
    sta $d900,x
    sta $da00,x
    sta $db00,x
    inx
    bne init_colors
    ldx #28
    lda #$0e
plane_colors:
!for row,5,16 {
    sta $0400+row*40+6,x
    sta $4400+row*40+6,x
}
    dex
    bpl plane_colors
    lda #6
    sta $d021
    ; Expand the initial lossless tile dictionary into both bitmaps.
    lda #0
    sta $fd
    sta $f9
    lda #$20
    sta $fe
    lda #$60
    sta $fa
    lda #$e8
    sta init_count
    lda #3
    sta init_count+1
    ldx #0
base_tile:
base_low:
    lda tile_lo,x
    sta $fb
base_high:
    lda tile_hi,x
    sta $fc
    ldy #7
base_pixels:
    lda ($fb),y
    sta ($fd),y
    sta ($f9),y
    dey
    bpl base_pixels
    clc
    lda $fd
    adc #8
    sta $fd
    sta $f9
    bcc same_page
    inc $fe
    inc $fa
same_page:
    inx
    bne same_map_page
    inc base_low+2
    inc base_high+2
same_map_page:
    lda init_count
    bne low_count
    dec init_count+1
low_count:
    dec init_count
    lda init_count
    ora init_count+1
    bne base_tile
    ldx #95
copy_frequencies:
    lda $02a6
    beq ntsc_frequency
    lda pal_lo,x
    sta freq_lo,x
    lda pal_hi,x
    sta freq_hi,x
    jmp next_frequency
ntsc_frequency:
    lda ntsc_lo,x
    sta freq_lo,x
    lda ntsc_hi,x
    sta freq_hi,x
next_frequency:
    dex
    bpl copy_frequencies
    jsr initialize_sid
    jsr sequence_step
    lda #$3b
    sta $d011
    rts

wait_frame:
    lda #250
wait_line:
    cmp $d012
    bne wait_line
leave_line:
    cmp $d012
    beq leave_line
    rts

; Forty-one tiles per tick leave time for music and KERNAL IRQs.
prepare_part:
    lda $01
    pha
    and #$fe
    sta $01
    lda phase
    asl
    asl
    clc
    adc render_part
    tay
    lda source_lo,y
    sta $fb
    lda source_hi,y
    sta $fc
    ldx render_part
    lda group_start,x
    tax
    lda #41
    sta tiles_left
patch_tile:
    lda patch_lo,x
    sta $fd
    lda patch_hi,x
    eor hidden_mask
    sta $fe
    ldy #7
patch_pixels:
    lda ($fb),y
    sta ($fd),y
    dey
    bpl patch_pixels
    clc
    lda $fb
    adc #8
    sta $fb
    bcc source_same_page
    inc $fc
source_same_page:
    inx
    dec tiles_left
    bne patch_tile
    pla
    sta $01
    inc render_part
    lda render_part
    cmp #4
    bcc part_done
    lda #0
    sta render_part
    lda #1
    sta pending
part_done:
    rts

flip:
    lda old_bank
    and #$fc
    ldx hidden_mask
    beq select_bank_zero
    ora #2
    bne select_bank
select_bank_zero:
    ora #3
select_bank:
    sta $dd00
    lda hidden_mask
    eor #$40
    sta hidden_mask
    lda #0
    sta pending
    lda speed_delay
    sta delay_count
    inc phase
    lda phase
    cmp #12
    bcc flip_done
    lda #0
    sta phase
flip_done:
    rts

music_tick:
    inc unit_tick
    lda unit_tick
    cmp frames_per_unit
    bcc instrument_tick
    lda #0
    sta unit_tick
    inc song_step
    jsr sequence_step
instrument_tick:
    lda muted
    bne tick_done
    ; Release the lead just before a new note, but sustain across tied steps.
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_envelope
    ldx song_step
    inx
    lda melody,x
    beq drum_envelope
    lda #$40
    sta $d404
drum_envelope:
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_release
    lda song_step
    and #1
    beq drum_release
    lda #$40
    sta $d40b
drum_release:
    lda unit_tick
    cmp #2
    bne pulse_motion
    lda drum_release_control
    sta $d412
pulse_motion:
    lda drum_release_control
    cmp #$10
    bne lead_motion
    lda unit_tick
    cmp #1
    bne lead_motion
    lda #6
    sta $d40f
lead_motion:
    lda unit_tick
    asl
    asl
    clc
    adc #$40
    sta $d402
tick_done:
    rts

sequence_step:
    ; Original C-major Eurodance theme; alternating five/six 50 Hz ticks.
    lda song_step
    and #1
    clc
    adc base_frames
    sta frames_per_unit
    lda muted
    beq audible_step
    jmp sequence_done
audible_step:
    ldx song_step
    lda melody,x
    beq accompaniment
    cmp #255
    bne lead_note
    lda #$40
    sta $d404
    jmp accompaniment
lead_note:
    tax
    lda freq_lo,x
    sta $d400
    lda freq_hi,x
    sta $d401
    lda #$41
    sta $d404
accompaniment:
    lda song_step
    and #1
    bne sequence_done
    ; Syncopated pulse bass, with a separate kick/snare/hi-hat voice.
    ldx song_step
    lda bass_notes,x
    tax
    lda freq_lo,x
    sta $d407
    lda freq_hi,x
    sta $d408
    lda #$41
    sta $d40b
    lda song_step
    and #3
    beq strong_drum
    ; Closed hi-hat on the off-beat.
    lda #$30
    sta $d40e
    lda #$38
    sta $d40f
    lda #$01
    sta $d413
    lda #$81
    bne play_drum
strong_drum:
    lda song_step
    and #7
    beq kick_drum
    lda #$40
    sta $d40e
    lda #$10
    sta $d40f
    lda #$04
    sta $d413
    lda #$81
    bne play_drum
kick_drum:
    lda #0
    sta $d40e
    lda #$0c
    sta $d40f
    lda #$02
    sta $d413
    lda #$11
play_drum:
    sta $d412
    and #$fe
    sta drum_release_control
sequence_done:
    rts

initialize_sid:
    ldx #24
clear_sid:
    lda #0
    sta $d400,x
    dex
    bpl clear_sid
    lda #$08
    sta $d405
    lda #$89
    sta $d406
    lda #$40
    sta $d402
    lda #$08
    sta $d403
    lda #$09
    sta $d40c
    lda #$48
    sta $d40d
    lda #$08
    sta $d40a
    lda #$08
    sta $d414
    lda #15
    sta $d418
    rts


controls:
    jsr $ffe4
    cmp #81
    bne check_pause
    lda #1
    sta quitting
    rts
check_pause:
    cmp #32
    bne check_mute
    lda paused
    eor #1
    sta paused
    bne quiet
    lda muted
    bne controls_done
    lda #15
    sta $d418
    rts
check_mute:
    cmp #77
    bne check_restart
    lda muted
    eor #1
    sta muted
    bne quiet
    lda paused
    bne quiet
    jsr initialize_sid
    jsr sequence_step
    rts
quiet:
    lda #0
    sta $d418
    rts
check_restart:
    cmp #82
    bne speed_one
    lda #0
    sta song_step
    sta unit_tick
    jsr sequence_step
    rts
speed_one:
    cmp #49
    bne speed_two
    lda #4
    sta speed_delay
    rts
speed_two:
    cmp #50
    bne speed_three
    lda #1
    sta speed_delay
    rts
speed_three:
    cmp #51
    bne controls_done
    lda #0
    sta speed_delay
controls_done:
    rts

silence_sid:
    ldx #24
    lda #0
silence_loop:
    sta $d400,x
    dex
    bpl silence_loop
    rts


show_splash:
    lda #<splash
    sta $fb
    lda #>splash
    sta $fc
print_splash:
    ldy #0
    lda ($fb),y
    beq wait_space
    jsr $ffd2
    inc $fb
    bne print_splash
    inc $fc
    jmp print_splash
wait_space:
    jsr $ffe4
    cmp #32
    bne wait_space
    rts

exit:
    lda #0
    sta $d015
    sta $d418
    jsr silence_sid
    ldx #0
restore_pointers:
    lda old_pointers,x
    sta $07f8,x
    inx
    cpx #8
    bne restore_pointers
    ldx #0
restore_extra:
    lda old_extra,x
    sta $d01b,x
    inx
    cpx #20
    bne restore_extra
    ldx #0
restore_vic:
    lda old_vic,x
    sta $d000,x
    inx
    cpx #25
    bne restore_vic
    lda old_bank
    sta $dd00
    lda old_text_color
    sta $0286
    lda #147
    jsr $ffd2
    ldx #0
restore_zp:
    lda old_zp,x
    sta $f9,x
    inx
    cpx #6
    bne restore_zp
    rts



