    inx
    cpx #25
    bne restore_vic
    lda old_bank
    sta $dd00
    lda old_text_color
    sta $0286
    lda #147
    jsr $ffd2
    ldx #0
restore_zp:
    lda old_zp,x
    sta $fb,x
    inx
    cpx #4
    bne restore_zp
    rts


