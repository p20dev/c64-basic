    cmp #49
    bne not_one
    lda #1
    sta speed
not_one:
    cmp #50
    bne not_two
    lda #2
    sta speed
not_two:
    cmp #51
    bne not_three
    lda #3
    sta speed
not_three:
    lda paused
    bne loop
    lda phase
    clc
    adc speed
    and #31
    sta phase
    jsr render
    jsr flip
    jmp loop

; Build all 1000 cells off screen. Fixed color RAM avoids visible color tearing.
render:
    lda #<field
    sta $fb
    lda #>field
    sta $fc
    lda #0
    sta $fd
    lda back_hi
    sta $fe
    ldx #4
    ldy #0
render_cell:
    lda ($fb),y
    sta cell
    and #31
    clc
    adc phase
    and #31
    sta value
    lda cell
    and #$e0
    ora value
    sta ($fd),y
    iny
    bne check_end
    inc $fc
    inc $fe
    dex
check_end:
    cpx #1
    bne render_cell
    cpy #232
    bne render_cell
    rts
flip:
    ; Flip only in the lower border, on both PAL and NTSC.
    lda #250
wait_enter:
    cmp $d012
    bne wait_enter
    lda back_hi
    cmp #12
    beq show_second
    lda #$18
    sta $d018
    lda #12
    sta back_hi
    rts
show_second:
    lda #$38
    sta $d018
    lda #4
    sta back_hi
    rts
exit:
    lda old_bank
    sta $dd00
    lda old_layout
    sta $d018
    lda old_scroll
    sta $d016
    lda old_sprites
    sta $d015
    ldx #6
restore_colors:
    lda old_colors,x
    sta $d020,x
    dex
    bpl restore_colors
    lda #147
    jsr $ffd2
    rts

