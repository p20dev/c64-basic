!cpu 6510
; PRISM SANCTUARY -- original faceted crystal and three-voice SID score.
; Twelve projected phases of a hexagonal bipyramid: shaded triangular faces,
; bright edges, a compressed dithered reflection and a perspective floor.
; The geometry repeats after 60 degrees; twelve phases give 5-degree steps.
; Every changing tile has its own glyph. 67 shared background glyphs use
; nearest two-bit-pixel distance to approximate static floor lines.
; No ROM glyphs in the scene. Two character buffers are filled in halves,
; then flipped only at raster 250. Each half costs about 10500 cycles.
; KERNAL IRQs, CIA timers and vectors remain untouched. BASIC ROM is banked
; out only during copying; the CPU port is restored immediately afterward.
; Separate PAL/NTSC SID tuning and 50 Hz music/movement normalization.
; SID is silenced on exit: write-only registers cannot restore a prior tune.
; Layout: launcher $0801, code $1000, buffers $2000/$2800, sprites $3000,
; screen/music/tables $4000, twelve charset frames $6000-$bfff.

* = $0801
!word basic_end,10
!byte $9e
!text "4096"
!byte 0
basic_end: !word 0

* = $1000
start:
    jsr save_state
    lda #0
    sta $d020
    sta $d021
    lda #147
    jsr $ffd2
    jsr show_splash
    jsr initialize
main:
    jsr wait_frame
    jsr controls
    lda quitting
    beq continue
    jmp exit
continue:
    lda paused
    bne main
    lda pending
    beq no_flip
    jsr flip
no_flip:
    lda $02a6
    bne tick
    inc ntsc_divider
    lda ntsc_divider
    cmp #6
    bcc tick
    lda #0
    sta ntsc_divider
    jmp main
tick:
    jsr music_tick
    jsr move_sparks
    lda delay_count
    beq draw
    dec delay_count
    jmp main
draw:
    jsr prepare_half
    jmp main

save_state:
    ldx #0
save_positions:
    lda $d000,x
    sta old_vic,x
    inx
    cpx #25
    bne save_positions
    ldx #0
save_extra:
    lda $d01b,x
    sta old_extra,x
    inx
    cpx #20
    bne save_extra
    ldx #0
save_pointers:
    lda $07f8,x
    sta old_pointers,x
    inx
    cpx #8
    bne save_pointers
    ldx #0
save_zp:
    lda $fb,x
    sta old_zp,x
    inx
    cpx #4
    bne save_zp
    lda $dd00
    sta old_bank
    lda $0286
    sta old_text_color
    rts


initialize:
    lda #0
    sta paused
    sta muted
    sta quitting
    sta song_step
    sta unit_tick
    sta ntsc_divider
    sta phase
    sta half
    sta pending
    sta orbit
    sta palette
    sta delay_count
    sta $d015
    lda #1
    sta speed_delay
    lda #5
    sta base_frames
    sta frames_per_unit
    lda old_bank
    ora #3
    sta $dd00
    lda #$1b
    sta $d011
    lda #$18
    sta $d016
    sta $d018
    lda #$28
    sta hidden
    jsr set_palette
    ldx #0
copy_scene:
    lda scene_screen,x
    sta $0400,x
    lda scene_screen+256,x
    sta $0500,x
    lda scene_screen+512,x
    sta $0600,x
    lda scene_screen+768,x
    sta $0700,x
    lda scene_colors,x
    sta $d800,x
    lda scene_colors+256,x
    sta $d900,x
    lda scene_colors+512,x
    sta $da00,x
    lda scene_colors+768,x
    sta $db00,x
    inx
    bne copy_scene
    ; Both buffers initially contain phase zero.
    ldx #0
initial_chars:
!for page,0,7 {
    lda frames+page*256,x
    sta $2000+page*256,x
    sta $2800+page*256,x
}
    inx
    bne initial_chars
    inc phase
    ldx #95
frequencies:
    lda $02a6
    beq ntsc
    lda pal_lo,x
    sta freq_lo,x
    lda pal_hi,x
    sta freq_hi,x
    jmp next_frequency
ntsc:
    lda ntsc_lo,x
    sta freq_lo,x
    lda ntsc_hi,x
    sta freq_hi,x
next_frequency:
    dex
    bpl frequencies
    lda #0
    sta $d010
    sta $d017
    sta $d01d
    sta $d01c
    lda #$c0
    sta $07f8
    lda #$c1
    sta $07f9
    lda #$c2
    sta $07fa
    lda #1
    sta $d027
    lda #3
    sta $d028
    lda #14
    sta $d029
    jsr initialize_sid
    jsr sequence_step
    jsr move_sparks
    lda #7
    sta $d015
    rts

wait_frame:
    lda #250
wait_line:
    cmp $d012
    bne wait_line
leave_line:
    cmp $d012
    beq leave_line
    rts

; Four unrolled indexed loads/stores per X keep this below one NTSC frame.
prepare_half:
    lda $01
    pha
    and #$fe
    sta $01
    ldx phase
    lda frame_hi,x
    clc
    adc half
    sta read0+2
    clc
    adc #1
    sta read1+2
    clc
    adc #1
    sta read2+2
    clc
    adc #1
    sta read3+2
    lda hidden
    clc
    adc half
    sta write0+2
    clc
    adc #1
    sta write1+2
    clc
    adc #1
    sta write2+2
    clc
    adc #1
    sta write3+2
    ldx #0
copy_half:
read0: lda $6000,x
write0: sta $2800,x
read1: lda $6100,x
write1: sta $2900,x
read2: lda $6200,x
write2: sta $2a00,x
read3: lda $6300,x
write3: sta $2b00,x
    inx
    bne copy_half
    pla
    sta $01
    lda half
    eor #4
    sta half
    bne half_done
    lda #1
    sta pending
half_done:
    rts

flip:
    lda hidden
    cmp #$28
    bne show_first
    lda #$1a
    sta $d018
    lda #$20
    bne next_hidden
show_first:
    lda #$18
    sta $d018
    lda #$28
next_hidden:
    sta hidden
    lda #0
    sta pending
    lda speed_delay
    sta delay_count
    inc phase
    lda phase
    cmp #12
    bcc flip_done
    lda #0
    sta phase
flip_done:
    rts

move_sparks:
    inc orbit
    ldx orbit
    lda spark_x,x
    sta $d000
    lda spark_y,x
    sta $d001
    lda spark_msb,x
    sta msb
    lda spark_depth,x
    sta depth
    txa
    clc
    adc #85
    tax
    lda spark_x,x
    sta $d002
    lda spark_y,x
    sta $d003
    lda spark_msb,x
    asl
    ora msb
    sta msb
    lda spark_depth,x
    asl
    ora depth
    sta depth
    txa
    clc
    adc #85
    tax
    lda spark_x,x
    sta $d004
    lda spark_y,x
    sta $d005
    lda spark_msb,x
    asl
    asl
    ora msb
    sta $d010
    lda spark_depth,x
    asl
    asl
    ora depth
    sta $d01b
    rts

set_palette:
    ldx palette
    lda palette_a,x
    sta $d022
    lda palette_b,x
    sta $d023
    rts

music_tick:
    inc unit_tick
    lda unit_tick
    cmp frames_per_unit
    bcc instrument_tick
    lda #0
    sta unit_tick
    inc song_step
    jsr sequence_step
instrument_tick:
    lda muted
    bne tick_done
    ; Release the lead just before a new note, but sustain across tied steps.
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_envelope
    ldx song_step
    inx
    lda melody,x
    beq drum_envelope
    lda #$10
    sta $d404
drum_envelope:
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_release
    lda song_step
    and #1
    beq drum_release
    lda #$40
    sta $d40b
drum_release:
    lda unit_tick
    cmp #2
    bne pulse_motion
    lda drum_release_control
    sta $d412
pulse_motion:
    lda drum_release_control
    cmp #$10
    bne lead_motion
    lda unit_tick
    cmp #1
    bne lead_motion
    lda #6
    sta $d40f
lead_motion:
    lda unit_tick
    asl
    asl
    clc
    adc #$40
    sta $d402
tick_done:
    rts

sequence_step:
    ; Original F-sharp-minor theme; alternating five/six 50 Hz ticks.
    lda song_step
    and #1
    clc
    adc base_frames
    sta frames_per_unit
    lda muted
    beq audible_step
    jmp sequence_done
audible_step:
    ldx song_step
    lda melody,x
    beq accompaniment
    cmp #255
    bne lead_note
    lda #$10
    sta $d404
    jmp accompaniment
lead_note:
    tax
    lda freq_lo,x
    sta $d400
    lda freq_hi,x
    sta $d401
    lda #$11
    sta $d404
accompaniment:
    lda song_step
    and #1
    bne sequence_done
    ; Syncopated pulse bass, with a separate kick/snare/hi-hat voice.
    ldx song_step
    lda bass_notes,x
    tax
    lda freq_lo,x
    sta $d407
    lda freq_hi,x
    sta $d408
    lda #$41
    sta $d40b
    lda song_step
    and #3
    beq strong_drum
    ; Closed hi-hat on the off-beat.
    lda #$30
    sta $d40e
    lda #$38
    sta $d40f
    lda #$01
    sta $d413
    lda #$81
    bne play_drum
strong_drum:
    lda song_step
    and #7
    beq kick_drum
    lda #$40
    sta $d40e
    lda #$10
    sta $d40f
    lda #$04
    sta $d413
    lda #$81
    bne play_drum
kick_drum:
    lda #0
    sta $d40e
    lda #$0c
    sta $d40f
    lda #$02
    sta $d413
    lda #$11
play_drum:
    sta $d412
    and #$fe
    sta drum_release_control
sequence_done:
    rts

initialize_sid:
    ldx #24
clear_sid:
    lda #0
    sta $d400,x
    dex
    bpl clear_sid
    lda #$08
    sta $d405
    lda #$89
    sta $d406
    lda #$40
    sta $d402
    lda #$08
    sta $d403
    lda #$09
    sta $d40c
    lda #$48
    sta $d40d
    lda #$08
    sta $d40a
    lda #$08
    sta $d414
    lda #15
    sta $d418
    rts


controls:
    jsr $ffe4
    cmp #81
    bne check_pause
    lda #1
    sta quitting
    rts
check_pause:
    cmp #32
    bne check_mute
    lda paused
    eor #1
    sta paused
    bne quiet
    lda muted
    bne controls_done
    lda #15
    sta $d418
    rts
check_mute:
    cmp #77
    bne check_palette
    lda muted
    eor #1
    sta muted
    bne quiet
    lda paused
    bne quiet
    jsr initialize_sid
    jsr sequence_step
    rts
quiet:
    lda #0
    sta $d418
    rts
check_palette:
    cmp #67
    bne check_restart
    inc palette
    lda palette
    cmp #3
    bcc apply_palette
    lda #0
    sta palette
apply_palette:
    jsr set_palette
    rts
check_restart:
    cmp #82
    bne speed_one
    lda #0
    sta song_step
    sta unit_tick
    jsr sequence_step
    rts
speed_one:
    cmp #49
    bne speed_two
    lda #4
    sta speed_delay
    rts
speed_two:
    cmp #50
    bne speed_three
    lda #1
    sta speed_delay
    rts
speed_three:
    cmp #51
    bne controls_done
    lda #0
    sta speed_delay
controls_done:
    rts

silence_sid:
    ldx #24
    lda #0
silence_loop:
    sta $d400,x
    dex
    bpl silence_loop
    rts

show_splash:
    lda #<splash
    sta $fb
    lda #>splash
    sta $fc
print_splash:
    ldy #0
    lda ($fb),y
    beq wait_space
    jsr $ffd2
    inc $fb
    bne print_splash
    inc $fc
    jmp print_splash
wait_space:
    jsr $ffe4
    cmp #32
    bne wait_space
    rts

exit:
    lda #0
    sta $d015
    sta $d418
    jsr silence_sid
    ldx #0
restore_pointers:
    lda old_pointers,x
    sta $07f8,x
    inx
    cpx #8
    bne restore_pointers
    ldx #0
restore_extra:
