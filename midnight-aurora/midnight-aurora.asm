!cpu 6510
; MIDNIGHT AURORA -- original multicolor bitmap landscape and SID score.
; 160x200 logical pixels: flowing curtains above snow peaks and a dark lake.
; Exact pixels, no ROM glyphs and no lossy character-pattern approximation.
; Two VIC banks: bitmap $2000 / screen $0400, bitmap $6000 / screen $4400.
; Only the 196 changing 8-byte tiles are copied: 49 tiles per 50 Hz tick.
; The next complete image is selected in the lower border at raster 250.
; BASIC ROM is banked out only while copying patch data at $8000-$c97f.
; CPU port restored immediately; KERNAL IRQs/timers/vectors are untouched.
; Twelve cyclic phases share a lossless base image. PAL/NTSC pitch tables.
; The three-voice music is original: pulse melody, triangle bass, pulse arp.
; Pause stops rendering, bank flips, sequencing and sound. Q silences SID
; (its write-only registers cannot recover a prior tune) and restores VIC.
; Code $1000, music $4000, base glyphs $4800, base pointers $5400/$5800,
; pitch/patch tables $5c00, patch frames $8000. No data enters the I/O area.

