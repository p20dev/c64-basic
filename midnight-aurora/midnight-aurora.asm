!for row,2,7 {
    sta $d800+row*40+5,x
}
    lda #$5d
!for row,2,7 {
    sta $0400+row*40+5,x
    sta $4400+row*40+5,x
}
    dex
    bpl aurora_colors
    ldx #29
    lda #$65
reflection_colors:
!for row,22,24 {
    sta $0400+row*40+5,x
    sta $4400+row*40+5,x
}
    dex
    bpl reflection_colors
    ldx #39
    lda #3
lake_colors:
!for row,17,24 {
    sta $d800+row*40,x
}
    dex
    bpl lake_colors
