    sta phase
    sta speed_delay
    lda #8
    sta frames_per_unit
    lda #$40
    sta hidden_mask
    lda old_bank
    ora #3
    sta $dd00
    lda #$18
    sta $d018
    sta $d016
    ; Static per-cell colors are identical in both VIC banks.
    ldx #0
init_colors:
    lda #$6e
    sta $0400,x
    sta $0500,x
    sta $0600,x
    sta $0700,x
    sta $4400,x
    sta $4500,x
    sta $4600,x
    sta $4700,x
    lda #1
    sta $d800,x
    sta $d900,x
    sta $da00,x
    sta $db00,x
    inx
    bne init_colors
    ldx #29
aurora_colors:
