    lda #0
    sta $fd
    sta $f9
    lda #$20
    sta $fe
    lda #$60
    sta $fa
    lda #$e8
    sta init_count
    lda #3
    sta init_count+1
    ldx #0
base_tile:
base_low:
    lda tile_lo,x
    sta $fb
base_high:
    lda tile_hi,x
    sta $fc
    ldy #7
base_pixels:
    lda ($fb),y
    sta ($fd),y
    sta ($f9),y
    dey
    bpl base_pixels
    clc
    lda $fd
    adc #8
    sta $fd
    sta $f9
    bcc same_page
    inc $fe
    inc $fa
same_page:
    inx
    bne same_map_page
    inc base_low+2
    inc base_high+2
same_map_page:
    lda init_count
    bne low_count
    dec init_count+1
low_count:
    dec init_count
    lda init_count
    ora init_count+1
    bne base_tile
    ldx #95
copy_frequencies:
    lda $02a6
    beq ntsc_frequency
    lda pal_lo,x
    sta freq_lo,x
    lda pal_hi,x
    sta freq_hi,x
    jmp next_frequency
ntsc_frequency:
    lda ntsc_lo,x
    sta freq_lo,x
    lda ntsc_hi,x
    sta freq_hi,x
next_frequency:
    dex
    bpl copy_frequencies
    jsr initialize_sid
    jsr sequence_step
    lda #$3b
    sta $d011
    rts

wait_frame:
    lda #250
wait_line:
    cmp $d012
    bne wait_line
leave_line:
    cmp $d012
    beq leave_line
    rts

; 49 tiles * (8 pixel copies plus addressing) fits comfortably in one frame.
prepare_part:
    lda $01
    pha
    and #$fe
    sta $01
    lda phase
    asl
    asl
    clc
    adc render_part
    tay
    lda source_lo,y
    sta $fb
    lda source_hi,y
    sta $fc
    ldx render_part
    lda group_start,x
    tax
    lda #49
    sta tiles_left
patch_tile:
    lda patch_lo,x
    sta $fd
    lda patch_hi,x
    eor hidden_mask
    sta $fe
    ldy #7
patch_pixels:
    lda ($fb),y
    sta ($fd),y
    dey
    bpl patch_pixels
    clc
    lda $fb
    adc #8
    sta $fb
    bcc source_same_page
    inc $fc
source_same_page:
    inx
    dec tiles_left
    bne patch_tile
    pla
    sta $01
    inc render_part
    lda render_part
    cmp #4
    bcc part_done
    lda #0
    sta render_part
    lda #1
    sta pending
part_done:
    rts

flip:
    lda old_bank
    and #$fc
    ldx hidden_mask
    beq select_bank_zero
    ora #2
    bne select_bank
select_bank_zero:
    ora #3
select_bank:
    sta $dd00
    lda hidden_mask
    eor #$40
    sta hidden_mask
    lda #0
    sta pending
    lda speed_delay
    sta delay_count
    inc phase
    lda phase
    cmp #12
    bcc flip_done
    lda #0
    sta phase
flip_done:
    rts

music_tick:
    inc unit_tick
    lda unit_tick
    cmp frames_per_unit
    bcc shape_notes
    lda #0
    sta unit_tick
    inc song_step
    jsr sequence_step
shape_notes:
    lda muted
    bne music_done
    ; One quiet tick before each arp attack. Lead ties are preserved.
    lda unit_tick
    cmp #7
    bne pulse_motion
    lda #$40
    sta $d412
    ldx song_step
    inx
    lda melody,x
    beq bass_release
    lda #$40
    sta $d404
bass_release:
    txa
    and #3
    bne pulse_motion
    lda #$10
    sta $d40b
pulse_motion:
    lda song_step
    and #31
    asl
    asl
    sta $d402
music_done:
    rts

sequence_step:
    lda muted
    beq audible
    rts
audible:
    ldx song_step
    lda melody,x
    beq bass_step
    cmp #255
    bne lead_note
    lda #$40
    sta $d404
    jmp bass_step
lead_note:
    tax
    lda freq_lo,x
    sta $d400
    lda freq_hi,x
    sta $d401
    lda #$41
    sta $d404
bass_step:
    lda song_step
    and #3
    bne arp_step
    ldx song_step
    lda bass_notes,x
    tax
    lda freq_lo,x
    sta $d407
    lda freq_hi,x
    sta $d408
    lda #$11
    sta $d40b
arp_step:
    ldx song_step
    lda arp_notes,x
    tax
    lda freq_lo,x
    sta $d40e
    lda freq_hi,x
    sta $d40f
    lda #$41
    sta $d412
    rts

initialize_sid:
    jsr silence_sid
    lda #$29
    sta $d405
    lda #$a9
    sta $d406
    lda #8
    sta $d403
    lda #$18
