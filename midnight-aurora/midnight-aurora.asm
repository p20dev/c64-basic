    lda #$03
    sta $d411
    lda #15
    sta $d418
    rts

controls:
    jsr $ffe4
    cmp #81
    bne check_pause
    lda #1
    sta quitting
    rts
check_pause:
    cmp #32
    bne check_mute
    lda paused
    eor #1
    sta paused
    bne quiet
    lda muted
    bne controls_done
    lda #15
    sta $d418
    rts
check_mute:
    cmp #77
    bne check_restart
    lda muted
    eor #1
    sta muted
    bne quiet
    lda paused
    bne quiet
    jsr initialize_sid
    jsr sequence_step
    rts
quiet:
    lda #0
    sta $d418
    rts
check_restart:
    cmp #82
    bne speed_one
    lda #0
    sta song_step
    sta unit_tick
    jsr sequence_step
    rts
speed_one:
    cmp #49
    bne speed_two
    lda #4
    sta speed_delay
    rts
speed_two:
    cmp #50
    bne speed_three
    lda #1
    sta speed_delay
    rts
speed_three:
    cmp #51
    bne controls_done
    lda #0
    sta speed_delay
controls_done:
    rts

silence_sid:
    ldx #24
    lda #0
silence_loop:
    sta $d400,x
    dex
    bpl silence_loop
    rts


show_splash:
    lda #<splash
    sta $fb
    lda #>splash
    sta $fc
print_splash:
    ldy #0
    lda ($fb),y
    beq wait_space
    jsr $ffd2
    inc $fb
    bne print_splash
    inc $fc
    jmp print_splash
wait_space:
    jsr $ffe4
    cmp #32
    bne wait_space
    rts

exit:
    lda #0
    sta $d015
    sta $d418
    jsr silence_sid
    ldx #0
