; SID arrangement: intro hook and chorus melody of Never Gonna Give You Up.
; Song: Mike Stock, Matt Aitken and Pete Waterman; performed by Rick Astley.
; Visual reference: https://www.youtube.com/watch?v=dQw4w9WgXc
; Pitch/rhythm cross-check: Robson Couto's arduino-songs transcription:
; https://github.com/robsoncouto/arduino-songs/tree/master/nevergonnagiveyouup
; New SID orchestration, bass groove and percussion. No samples or lyrics.
; Layout: code $1000, custom charset $2000, four sprite poses $3000,
; scene and sequence data $4000. BASIC SYS launcher at $0801.

