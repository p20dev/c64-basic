    sta speed_delay
    lda #5
    sta base_frames
    sta frames_per_unit
    lda #140
    sta car_x
    lda #$0c
    sta hidden
    lda old_bank
    ora #3
    sta $dd00
    lda #$1b
    sta $d011
    lda #$18
    sta $d016
    sta $d018
    lda #14
    sta $d021
    lda #12
    sta $d022
    lda #1
    sta $d023
    jsr load_region
    ; Populate both hidden/visible road areas before showing the car.
    jsr render_road
    lda #4
    sta hidden
    jsr render_road
    lda #$0c
    sta hidden
    lda #0
    sta pending
    lda #$24
    sta $07f8
    sta $0ff8
    lda #$25
    sta $07f9
    sta $0ff9
    lda #0
    sta $d010
    sta $d01b
    lda #3
    sta $d017
    sta $d01d
    sta $d01c
    sta $d015
    lda #1
    sta $d025
    lda #0
    sta $d026
    lda #2
    sta $d027
    sta $d028
    lda #208
    sta $d001
    sta $d003
    jsr position_car
    ldx #95
copy_frequencies:
    lda $02a6
    beq ntsc_frequency
    lda pal_lo,x
    sta freq_lo,x
    lda pal_hi,x
    sta freq_hi,x
    jmp next_frequency
ntsc_frequency:
    lda ntsc_lo,x
    sta freq_lo,x
    lda ntsc_hi,x
    sta freq_hi,x
next_frequency:
    dex
    bpl copy_frequencies
    jsr initialize_sid
    jsr sequence_step
    rts

position_car:
    lda car_x
    sta $d000
    clc
    adc #48
    sta $d002
    rts

wait_frame:
    lda #250
wait_line:
    cmp $d012
    bne wait_line
leave_line:
    cmp $d012
    beq leave_line
    rts

render_road:
    lda $01
    pha
    and #$fe
    sta $01
    ldx phase
    lda frame_lo,x
    sta read_a+1
    sta read_b+1
    sta read_c+1
    lda frame_hi,x
    sta read_a+2
    clc
    adc #1
    sta read_b+2
    clc
    adc #1
    sta read_c+2
    lda hidden
    clc
    adc #1
    sta write_a+2
    clc
    adc #1
    sta write_b+2
    clc
    adc #1
    sta write_c+2
    ldx #0
road_pages:
read_a: lda $6000,x
write_a: sta $0d68,x
read_b: lda $6100,x
write_b: sta $0e68,x
    inx
    bne road_pages
    ldx #0
road_tail:
read_c: lda $6200,x
write_c: sta $0f68,x
    inx
    cpx #128
    bne road_tail
    pla
    sta $01
    lda #1
    sta pending
    rts

flip:
    lda hidden
    cmp #$0c
    bne first_screen
    lda #$30
    bne select_chars
first_screen:
    lda #$10
select_chars:
    sta screen_bits
    lda region
    asl
    ora #8
    ora screen_bits
    sta $d018
    lda hidden
    eor #8
    sta hidden
    lda #0
    sta pending
    lda speed_delay
    sta delay_count
    inc phase
    lda phase
    and #31
    sta phase
    inc region_age
    lda region_age
    cmp #128
    bcc flip_done
    jsr next_region
flip_done:
    rts

next_region:
    inc region
    lda region
    and #3
    sta region
    lda #0
    sta region_age
    jmp load_region

load_region:
    lda $01
    pha
    and #$fe
    sta $01
    lda $d011
    and #$ef
    sta $d011
    ldx region
    lda horizon_hi,x
    sta $fc
    lda #0
    sta $fb
    ldy #0
horizon_page:
    lda ($fb),y
    sta $0400,y
    sta $0c00,y
    iny
    bne horizon_page
    inc $fc
    ldy #0
horizon_tail:
    lda ($fb),y
    sta $0500,y
    sta $0d00,y
    iny
    cpy #104
    bne horizon_tail
    ldx region
    lda terrain_colors,x
    ldx #0
color_page:
    sta $d800,x
    sta $d900,x
    sta $da00,x
    sta $db00,x
    inx
    bne color_page
    lda $d018
    and #$f0
    sta screen_bits
    lda region
    asl
    ora #8
    ora screen_bits
    sta $d018
    lda #$1b
    sta $d011
    pla
    sta $01
    rts

music_tick:
    inc unit_tick
    lda unit_tick
    cmp frames_per_unit
    bcc instrument_tick
    lda #0
    sta unit_tick
    inc song_step
    jsr sequence_step
instrument_tick:
    lda muted
    bne tick_done
    ; Release the lead just before a new note, but sustain across tied steps.
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_envelope
    ldx song_step
    inx
    lda melody,x
    beq drum_envelope
    lda #$40
    sta $d404
drum_envelope:
    lda frames_per_unit
    sec
    sbc #1
    cmp unit_tick
    bne drum_release
    lda song_step
    and #1
    beq drum_release
    lda #$40
    sta $d40b
drum_release:
    lda unit_tick
    cmp #2
    bne pulse_motion
    lda drum_release_control
    sta $d412
pulse_motion:
    lda drum_release_control
    cmp #$10
    bne lead_motion
    lda unit_tick
    cmp #1
    bne lead_motion
    lda #6
    sta $d40f
lead_motion:
    lda unit_tick
    asl
    asl
    clc
    adc #$40
    sta $d402
tick_done:
    rts

sequence_step:
    ; Original F-major arcade-drive theme; alternating five/six 50 Hz ticks.
    lda song_step
    and #1
    clc
    adc base_frames
    sta frames_per_unit
    lda muted
    beq audible_step
    jmp sequence_done
audible_step:
    ldx song_step
    lda melody,x
    beq accompaniment
    cmp #255
    bne lead_note
    lda #$40
    sta $d404
    jmp accompaniment
lead_note:
    tax
    lda freq_lo,x
    sta $d400
    lda freq_hi,x
    sta $d401
    lda #$41
    sta $d404
accompaniment:
    lda song_step
    and #1
    bne sequence_done
    ; Syncopated pulse bass, with a separate kick/snare/hi-hat voice.
    ldx song_step
    lda bass_notes,x
    tax
    lda freq_lo,x
    sta $d407
    lda freq_hi,x
    sta $d408
    lda #$41
    sta $d40b
    lda song_step
    and #3
    beq strong_drum
    ; Closed hi-hat on the off-beat.
    lda #$30
    sta $d40e
    lda #$38
    sta $d40f
    lda #$01
    sta $d413
    lda #$81
    bne play_drum
strong_drum:
    lda song_step
    and #7
    beq kick_drum
    lda #$40
    sta $d40e
    lda #$10
    sta $d40f
    lda #$04
    sta $d413
    lda #$81
    bne play_drum
kick_drum:
    lda #0
    sta $d40e
    lda #$0c
    sta $d40f
    lda #$02
    sta $d413
    lda #$11
play_drum:
    sta $d412
    and #$fe
    sta drum_release_control
sequence_done:
    rts

initialize_sid:
    ldx #24
clear_sid:
    lda #0
    sta $d400,x
    dex
    bpl clear_sid
    lda #$08
    sta $d405
    lda #$89
    sta $d406
    lda #$40
    sta $d402
    lda #$08
    sta $d403
    lda #$09
    sta $d40c
    lda #$48
    sta $d40d
    lda #$08
    sta $d40a
    lda #$08
    sta $d414
    lda #15
    sta $d418
    rts



controls:
    jsr $ffe4
    cmp #81
    bne check_pause
    lda #1
    sta quitting
    rts
check_pause:
    cmp #32
    bne check_mute
    lda paused
    eor #1
    sta paused
    bne quiet
    lda muted
    beq control_resume
    rts
control_resume:
    lda #15
    sta $d418
    rts
check_mute:
    cmp #77
    bne check_region
    lda muted
    eor #1
    sta muted
    bne quiet
    lda paused
    bne quiet
    jsr initialize_sid
    jsr sequence_step
    rts
quiet:
    lda #0
    sta $d418
    rts
check_region:
    cmp #78
    bne check_left
    jsr next_region
    rts
check_left:
    cmp #65
    bne check_right
    lda car_x
    cmp #100
    bcs left_ok
    rts
left_ok:
    sec
    sbc #4
    sta car_x
    rts
check_right:
    cmp #68
    bne check_restart
    lda car_x
    cmp #192
    bcc right_ok
    rts
right_ok:
    clc
    adc #4
    sta car_x
    rts
check_restart:
    cmp #82
    bne speed_one
    lda #0
    sta song_step
    sta unit_tick
    jsr sequence_step
    rts
speed_one:
    cmp #49
    bne speed_two
    lda #5
    sta speed_delay
    rts
speed_two:
    cmp #50
    bne speed_three
    lda #2
    sta speed_delay
    rts
speed_three:
    cmp #51
    bne controls_done
    lda #1
    sta speed_delay
controls_done:
    rts

silence_sid:
    ldx #24
    lda #0
silence_loop:
    sta $d400,x
    dex
    bpl silence_loop
    rts



show_splash:
    lda #<splash
    sta $fb
    lda #>splash
    sta $fc
print_splash:
    ldy #0
    lda ($fb),y
    beq wait_space
    jsr $ffd2
    inc $fb
    bne print_splash
    inc $fc
    jmp print_splash
wait_space:
    jsr $ffe4
    cmp #32
    bne wait_space
    rts

exit:
    lda #0
    sta $d015
    sta $d418
    jsr silence_sid
    ldx #0
