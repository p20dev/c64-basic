basic_end: !word 0
* = $1000
start:
    jsr save_state
    lda #0
    sta $d020
    sta $d021
    lda #147
    jsr $ffd2
    jsr show_splash
    jsr initialize
main:
    jsr wait_frame
    jsr controls
    lda quitting
    beq continue
    jmp exit
continue:
    lda paused
    bne main
    jsr position_car
    lda pending
    beq no_flip
    jsr flip
no_flip:
    lda $02a6
    bne tick
    inc ntsc_divider
    lda ntsc_divider
    cmp #6
    bcc tick
    lda #0
    sta ntsc_divider
    jmp main
tick:
    jsr music_tick
    lda delay_count
    beq draw
    dec delay_count
    jmp main
draw:
    jsr render_road
    jmp main

save_state:
    ldx #0
save_positions:
    lda $d000,x
    sta old_vic,x
    inx
    cpx #25
    bne save_positions
    ldx #0
save_extra:
    lda $d01b,x
    sta old_extra,x
    inx
    cpx #20
    bne save_extra
    ldx #0
save_pointers:
    lda $07f8,x
    sta old_pointers,x
    inx
    cpx #8
    bne save_pointers
    ldx #0
save_zp:
    lda $f9,x
    sta old_zp,x
    inx
    cpx #6
    bne save_zp
    lda $dd00
    sta old_bank
    lda $0286
    sta old_text_color
    rts




initialize:
    lda #0
    sta $d015
    sta paused
    sta muted
    sta quitting
    sta pending
    sta phase
    sta region
    sta region_age
    sta song_step
    sta unit_tick
    sta ntsc_divider
    sta delay_count
