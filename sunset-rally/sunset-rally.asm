!cpu 6510
; SUNSET RALLY -- original touring-road demo with changing scenery.
; Forest, countryside, desert and mountains cycle forever; no race timer.
; Separate custom charsets, perspective road tiles and a two-sprite red car.
; Screen buffers $0400/$0c00 switch at raster 250. Road copying is hidden.
; Region cuts briefly blank the display while shared color RAM is replaced.
; KERNAL IRQs and CIA timers remain untouched; PAL/NTSC SID pitch tables.
; SID registers are write-only, so exit deliberately silences the chip.
; Original music and graphics, inspired by OutRun's touring atmosphere.
; Layout: SYS $1000, car $0900, charsets $2000-$3fff, score $4000,
; road frames $6000-$afff, four horizon maps $b000-$b7ff.
; Road glyphs use a nearest-pattern dictionary; no ROM letters in the scene.

* = $0801
